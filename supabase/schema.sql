-- Run this once in Supabase Dashboard → SQL Editor. This creates a fresh,
-- server-only database for Daily Earner; it does not import any local SQLite data.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null unique,
  password_hash text not null,
  trade_password_hash text not null,
  referral_code text not null unique,
  referred_by_id bigint references public.users(id),
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.sessions (
  token_hash text primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  expires_at bigint not null
);

create table if not exists public.wallets (
  user_id bigint primary key references public.users(id) on delete cascade,
  balance_ugx bigint not null default 0
);

create table if not exists public.wallet_transactions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  amount_ugx bigint not null,
  type text not null,
  reference text not null unique,
  description text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  recipient_user_id bigint not null references public.users(id) on delete cascade,
  sender_user_id bigint not null references public.users(id) on delete restrict,
  subject text not null,
  body text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.treasure_chests (
  id bigint generated by default as identity primary key,
  code text not null unique,
  reward_amount bigint not null check (reward_amount in (500, 1000, 2000, 5000, 10000)),
  currency text not null default 'UGX',
  assigned_user_id bigint not null references public.users(id) on delete cascade,
  status text not null default 'unused' check (status in ('unused', 'redeemed', 'expired')),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  redeemed_at timestamptz,
  redeemed_by bigint references public.users(id),
  created_by bigint not null references public.users(id)
);

create table if not exists public.marzpay_transactions (
  id uuid primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  reference text not null unique,
  marzpay_uuid text unique,
  phone text not null,
  amount_ugx bigint not null check (amount_ugx between 500 and 10000000),
  status text not null default 'pending' check (status in ('pending', 'paid', 'failed')),
  provider_tx_id text,
  provider_payload jsonb,
  credited_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Shared treasure campaigns: one code may be redeemed once by every account.
create table if not exists public.treasure_campaigns (
  id bigint generated by default as identity primary key,
  code text not null unique,
  max_reward_ugx bigint not null default 20000 check (max_reward_ugx between 500 and 20000),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  created_by bigint not null references public.users(id)
);

create table if not exists public.treasure_redemptions (
  campaign_id bigint not null references public.treasure_campaigns(id) on delete cascade,
  user_id bigint not null references public.users(id) on delete cascade,
  reward_amount bigint not null check (reward_amount between 500 and 20000),
  redeemed_at timestamptz not null default now(),
  primary key (campaign_id, user_id)
);

create index if not exists treasure_chests_assigned_status_idx
  on public.treasure_chests (assigned_user_id, status);
create index if not exists sessions_user_expires_idx
  on public.sessions (user_id, expires_at);
create index if not exists messages_recipient_created_idx
  on public.messages (recipient_user_id, created_at desc);
create index if not exists marzpay_transactions_user_created_idx
  on public.marzpay_transactions (user_id, created_at desc);
create index if not exists treasure_redemptions_user_idx
  on public.treasure_redemptions (user_id, redeemed_at desc);

-- Atomically redeems a code and credits the assigned wallet. This function is
-- server-only: the Vercel API calls it with the Supabase service-role key.
create or replace function public.redeem_treasure_chest(p_code text, p_user_id bigint)
returns table (reward_amount bigint, balance_ugx bigint)
language plpgsql
security definer
set search_path = public
as $$
declare
  chest public.treasure_chests%rowtype;
begin
  select * into chest from public.treasure_chests where code = upper(trim(p_code)) for update;
  if not found then raise exception 'Invalid Treasure Chest code.'; end if;
  if chest.assigned_user_id <> p_user_id then raise exception 'This code is not assigned to your account.'; end if;
  if chest.status = 'redeemed' then raise exception 'This Treasure Chest code has already been redeemed.'; end if;
  if chest.expires_at <= now() then
    update public.treasure_chests set status = 'expired' where id = chest.id and status = 'unused';
    raise exception 'This Treasure Chest code has expired.';
  end if;
  if chest.status <> 'unused' then raise exception 'This Treasure Chest code has expired.'; end if;

  update public.treasure_chests set status = 'redeemed', redeemed_at = now(), redeemed_by = p_user_id
    where id = chest.id and status = 'unused';
  update public.wallets set balance_ugx = balance_ugx + chest.reward_amount where user_id = p_user_id;
  insert into public.wallet_transactions (user_id, amount_ugx, type, reference, description, created_at)
    values (p_user_id, chest.reward_amount, 'treasure_reward', 'TREASURE-' || chest.code, 'Treasure Chest reward ' || chest.code, now());

  return query select chest.reward_amount, wallets.balance_ugx from public.wallets where user_id = p_user_id;
end;
$$;

revoke all on function public.redeem_treasure_chest(text, bigint) from public;
grant execute on function public.redeem_treasure_chest(text, bigint) to service_role;

create or replace function public.credit_marzpay_transaction(p_transaction_id uuid, p_provider_tx_id text, p_payload jsonb)
returns table (amount_ugx bigint, balance_ugx bigint)
language plpgsql
security definer
set search_path = public
as $$
declare
  payment public.marzpay_transactions%rowtype;
begin
  select * into payment from public.marzpay_transactions where id = p_transaction_id for update;
  if not found then raise exception 'Payment transaction not found.'; end if;
  update public.marzpay_transactions set status = 'paid', provider_tx_id = coalesce(p_provider_tx_id, provider_tx_id),
    provider_payload = p_payload, updated_at = now() where id = payment.id;
  if payment.credited_at is null then
    update public.wallets set balance_ugx = balance_ugx + payment.amount_ugx where user_id = payment.user_id;
    insert into public.wallet_transactions (user_id, amount_ugx, type, reference, description, created_at)
      values (payment.user_id, payment.amount_ugx, 'marzpay_deposit', 'MARZPAY-' || payment.reference, 'MarzPay wallet top-up', now());
    update public.marzpay_transactions set credited_at = now() where id = payment.id;
  end if;
  return query select payment.amount_ugx, wallets.balance_ugx from public.wallets where user_id = payment.user_id;
end;
$$;

revoke all on function public.credit_marzpay_transaction(uuid, text, jsonb) from public;
grant execute on function public.credit_marzpay_transaction(uuid, text, jsonb) to service_role;

create or replace function public.redeem_treasure_campaign(p_code text, p_user_id bigint)
returns table (reward_amount bigint, balance_ugx bigint)
language plpgsql
security definer
set search_path = public
as $$
declare
  campaign public.treasure_campaigns%rowtype;
  reward bigint;
begin
  select * into campaign from public.treasure_campaigns where code = upper(trim(p_code)) for update;
  if not found then raise exception 'Invalid Treasure Chest code.'; end if;
  if campaign.expires_at <= now() then raise exception 'This Treasure Chest code has expired.'; end if;
  if exists (select 1 from public.treasure_redemptions where campaign_id = campaign.id and user_id = p_user_id) then
    raise exception 'You have already redeemed this Treasure Chest code.';
  end if;
  -- Rewards are whole UGX 500 amounts, from 500 up to the campaign cap.
  reward := ((floor(random() * (campaign.max_reward_ugx / 500))::bigint) + 1) * 500;
  insert into public.treasure_redemptions (campaign_id, user_id, reward_amount) values (campaign.id, p_user_id, reward);
  update public.wallets set balance_ugx = balance_ugx + reward where user_id = p_user_id;
  insert into public.wallet_transactions (user_id, amount_ugx, type, reference, description, created_at)
    values (p_user_id, reward, 'treasure_reward', 'TREASURE-' || campaign.id || '-' || p_user_id, 'Shared Treasure Chest reward ' || campaign.code, now());
  return query select reward, wallets.balance_ugx from public.wallets where user_id = p_user_id;
end;
$$;

revoke all on function public.redeem_treasure_campaign(text, bigint) from public;
grant execute on function public.redeem_treasure_campaign(text, bigint) to service_role;

